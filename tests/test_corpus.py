"""Tests for the corpus builder.

The Stage 0 corpus is generated by scripts/make_smoke_corpus.py, and
every number in docs/STAGE0_RESULTS.md comes out of its manifests. A
silent text/audio misalignment there produces a WER number that looks
plausible and is completely wrong, which is exactly the bug these
tests exist to prevent.

The one that matters most is `test_clip_filename_encodes_its_text`:
`synthesize` skips a wav that already exists, so a filename that can
refer to two different sentences will keep stale audio and write new
text into the manifest.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "scripts" / "make_smoke_corpus.py"


def _load():
    spec = importlib.util.spec_from_file_location("make_smoke_corpus", CORPUS)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def corpus():
    return _load()


def test_clip_filename_encodes_its_text(corpus) -> None:
    """Two sentences must never share a filename.

    `synthesize` returns early when the wav exists, so a shared
    filename means the second sentence inherits the first sentence's
    audio. This is not hypothetical: it corrupted the eval_seen split
    before the text digest was added to the filename.
    """
    a = corpus._text_tag("The child jumped around the girl.")
    b = corpus._text_tag("The man started suddenly.")
    assert a != b
    assert a == corpus._text_tag("The child jumped around the girl.")
    assert len(a) == 8


def test_generated_sentences_are_grammatical_and_unique(corpus) -> None:
    """Every generated sentence must use a verb form we wrote out.

    The generator has no conjugation logic, so this catches a word
    list edit that introduces a malformed frame.
    """
    import random

    sentences = corpus.generate_sentences(120, random.Random(0), set())
    assert len(sentences) == len(set(sentences)) == 120
    for sentence in sentences:
        assert sentence.endswith(".")
        assert sentence[0].isupper()
        words = sentence[:-1].split()
        assert len(words) >= 3
        assert not any(w.endswith("ed ed") for w in words)


def test_train_and_eval_sentences_do_not_overlap(corpus) -> None:
    import random

    rng = random.Random(17)
    train_seed = corpus.HANDWRITTEN[: -corpus.N_HELD_OUT]
    held_out = corpus.HANDWRITTEN[-corpus.N_HELD_OUT :]

    eval_sentences = list(held_out) + corpus.generate_sentences(40, rng, set(train_seed))
    train_sentences = list(train_seed) + corpus.generate_sentences(220, rng, set(eval_sentences))

    assert not set(train_sentences) & set(eval_sentences)


def test_eval_sentences_are_the_held_out_handwritten_ones(corpus) -> None:
    assert len(corpus.HANDWRITTEN) - corpus.N_HELD_OUT == 20
    assert "The light faded slowly behind the hills." in corpus.HANDWRITTEN[-corpus.N_HELD_OUT :]


def test_train_and_eval_voices_are_disjoint(corpus) -> None:
    assert not set(corpus.TRAIN_VOICES) & set(corpus.EVAL_VOICES)


@pytest.mark.skipif(
    not (ROOT / "data" / "smoke" / "eval.jsonl").exists(),
    reason="corpus not generated; run scripts/make_smoke_corpus.py",
)
def test_generated_manifests_are_audio_text_aligned() -> None:
    """Decode a few eval clips and confirm the audio says what the
    manifest claims.

    This is the expensive version of the filename test: it runs the real
    Parakeet model, so it only runs when the extracted encoder is
    present, and it checks three clips because each decode takes about a
    second.
    """
    encoder_dir = ROOT / "artifacts" / "parakeet-encoder-v2"
    if not (encoder_dir / "model.safetensors").exists():
        pytest.skip("no extracted encoder")

    import soundfile as sf
    import torch
    from transformers import ParakeetEncoder, ParakeetFeatureExtractor

    feature_extractor = ParakeetFeatureExtractor.from_pretrained(str(encoder_dir))
    encoder = ParakeetEncoder.from_pretrained(str(encoder_dir)).eval()

    rows = [
        json.loads(line)
        for line in (ROOT / "data" / "smoke" / "eval.jsonl").read_text().splitlines()
        if line.strip()
    ][:3]

    with torch.no_grad():
        for row in rows:
            wav, _ = sf.read(row["audio_filepath"], dtype="float32")
            inputs = feature_extractor(wav, sampling_rate=16000, return_tensors="pt")
            feats = encoder(input_features=inputs["input_features"]).last_hidden_state
            assert feats.shape[0] == 1 and feats.shape[-1] == 1024
            # 8x subsampling of a 100 fps front end; the conv stack
            # rounds up, so allow one frame either way.
            assert abs(feats.shape[1] - len(wav) // (160 * 8)) <= 1
            # Frame content must not be constant: a corrupt or silent
            # clip produces near-zero variance across time.
            assert feats.std(dim=1).max().item() > 1e-3, (
                f"clip {Path(row['audio_filepath']).name} looks silent"
            )